/** Texto para una clave construida en tiempo de ejecución; si no existe, devuelve el valor tal cual. */
export function tDyn(lang: UiLang, key: string, fallback?: string): string {
  const e = (D as Record<string, Entry>)[key];
  if (!e) return fallback ?? key;
  return lang === "en" ? (EN as Record<string, string>)[key] ?? e.es : e[lang];
}

